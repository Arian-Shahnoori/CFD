import numpy as np


# =============================================================================
# Residual Norm
# =============================================================================

def residual_norm(T, N):

    dx = 1.0 / N

    residual = (
        T[2:N+2, 1:N+1]
        + T[0:N, 1:N+1]
        + T[1:N+1, 2:N+2]
        + T[1:N+1, 0:N]
        - 4 * T[1:N+1, 1:N+1]
    ) / dx**2

    return np.sqrt(np.mean(residual**2))